"""
Low-Latency Token Streaming and Incremental TTS Orchestrator for IRIS AI
=======================================================================
Coordinates concurrent token streaming, sentence/clause boundary buffering,
and early incremental TTS audio synthesis.

Key Pipeline:
  1. Streams text tokens from HybridModelRouter.
  2. Buffers text until natural clause/sentence boundaries: ['. ', '! ', '? ', '; ', '\\n', ', ' (if >=5 words)].
  3. Synthesizes Clause 0 to audio in background thread WHILE Clause 1 is being generated by LLM.
  4. Tags each audio chunk with the active generation ID and sequence index.
  5. Drops chunks instantly if BargeInManager triggers cancellation.
  6. Measures TTFT (Time to First Token), TTFA (Time to First Audio chunk), and total latency.
"""

import time
import re
import queue
import logging
import threading
from typing import Optional, Dict, Any, List, Generator, Callable
from backend.engine.barge_in_manager import get_barge_in_manager, BargeInManager
from backend.engine.hybrid_model_router import get_hybrid_router, HybridModelRouter

logger = logging.getLogger("iris.streaming_orchestrator")

# Boundary delimiters for natural speech chunks (protecting decimals like 3.14)
SENTENCE_SPLIT_REGEX = re.compile(r"(?<!\d)([.!?;\n]+)(?!\d)\s*")


class StreamingOrchestrator:
    """
    Coordinates concurrent LLM token streaming and incremental phrase/sentence TTS.
    """

    def __init__(self, hybrid_router: Optional[HybridModelRouter] = None, voice_engine=None):
        self.router = hybrid_router or get_hybrid_router()
        self.voice_engine = voice_engine
        self.barge_in_mgr: BargeInManager = get_barge_in_manager(voice_engine=voice_engine)

        # Performance metrics history
        self.metrics_history: List[Dict[str, Any]] = []

    def stream_chat_and_synthesize(
        self,
        messages: List[Dict[str, str]],
        system_prompt: Optional[str] = None,
        voice_preset: Optional[str] = None,
        synthesize_voice: bool = True,
        on_token: Optional[Callable[[str, str], Any]] = None,
        on_audio_chunk: Optional[Callable[[Dict[str, Any]], Any]] = None,
    ) -> Dict[str, Any]:
        """
        Orchestrates full token streaming and concurrent chunk audio synthesis.
        
        Args:
          messages: list of conversation messages
          system_prompt: optional system prompt
          voice_preset: voice preset name (e.g. andrew, ava)
          synthesize_voice: whether to generate incremental speech audio
          on_token: callback(token, generation_id)
          on_audio_chunk: callback(chunk_dict) containing {chunk_index, audio_path, text, gen_id, is_final}
          
        Returns:
          Telemetry summary containing total text, metrics, and provider info.
        """
        t0 = time.time()
        gen_id = self.barge_in_mgr.start_new_generation()

        # Telemetry stamps
        t_first_token: Optional[float] = None
        t_first_audio: Optional[float] = None

        full_text_accumulator: List[str] = []
        clause_buffer = ""
        chunk_sequence = 0
        provider_name = "unknown"
        model_name = "unknown"
        is_offline = False

        # Queue for concurrent TTS worker
        tts_queue: queue.Queue = queue.Queue()
        tts_finished = threading.Event()

        def tts_worker():
            nonlocal t_first_audio
            while True:
                item = tts_queue.get()
                if item is None:
                    tts_queue.task_done()
                    break

                chunk_idx, text_chunk, is_final = item
                if not self.barge_in_mgr.is_valid(gen_id):
                    logger.debug(f"Generation [{gen_id}] cancelled, discarding TTS chunk {chunk_idx}")
                    tts_queue.task_done()
                    continue

                if self.voice_engine and text_chunk.strip():
                    t_synth_start = time.perf_counter()
                    audio_file = None
                    try:
                        if hasattr(self.voice_engine, "synthesize_chunk_to_file"):
                            audio_file = self.voice_engine.synthesize_chunk_to_file(text_chunk)
                    except Exception as e:
                        logger.error(f"Error synthesizing chunk {chunk_idx}: {e}")

                    if self.barge_in_mgr.is_valid(gen_id) and audio_file:
                        if t_first_audio is None:
                            t_first_audio = time.time() - t0

                        chunk_payload = {
                            "chunk_index": chunk_idx,
                            "audio_path": audio_file,
                            "text": text_chunk,
                            "generation_id": gen_id,
                            "is_final": is_final,
                            "synth_latency_ms": round((time.perf_counter() - t_synth_start) * 1000.0, 1),
                        }
                        if on_audio_chunk:
                            try:
                                on_audio_chunk(chunk_payload)
                            except Exception as e:
                                logger.error(f"Error in on_audio_chunk callback: {e}")

                tts_queue.task_done()
            tts_finished.set()

        # Launch background TTS worker thread if speech synthesis is enabled
        worker_thread = None
        if synthesize_voice:
            worker_thread = threading.Thread(target=tts_worker, daemon=True)
            worker_thread.start()

        # Stream tokens from hybrid model router
        try:
            for chunk_data in self.router.chat_stream(messages, system_prompt=system_prompt):
                # Check for cancellation on every token
                if not self.barge_in_mgr.is_valid(gen_id):
                    logger.info(f"⚡ Token streaming aborted by barge-in for [{gen_id}]")
                    break

                token = chunk_data.get("token", "")
                provider_name = chunk_data.get("provider", provider_name)
                model_name = chunk_data.get("model", model_name)
                is_offline = chunk_data.get("is_offline", is_offline)

                if token:
                    if t_first_token is None:
                        t_first_token = time.time() - t0

                    full_text_accumulator.append(token)
                    clause_buffer += token

                    # Emit token to callback immediately for live UI rendering
                    if on_token:
                        try:
                            on_token(token, gen_id)
                        except Exception as e:
                            logger.error(f"Error in on_token callback: {e}")

                    # Check for sentence or clause boundary
                    if synthesize_voice:
                        match = SENTENCE_SPLIT_REGEX.search(clause_buffer)
                        # Split on sentence boundaries, or comma only if clause has at least 12 words
                        comma_split = (", " in clause_buffer and len(clause_buffer.split()) >= 12)
                        
                        if match or comma_split:
                            split_pos = match.end() if match else clause_buffer.find(", ") + 2
                            ready_clause = clause_buffer[:split_pos].strip()
                            if ready_clause and len(ready_clause.split()) >= 2:
                                clause_buffer = clause_buffer[split_pos:]
                                tts_queue.put((chunk_sequence, ready_clause, False))
                                chunk_sequence += 1

                if chunk_data.get("done", False):
                    break

        except Exception as e:
            logger.error(f"Error during token streaming: {e}")

        # Dispatch any remaining text in buffer
        if synthesize_voice and clause_buffer.strip() and self.barge_in_mgr.is_valid(gen_id):
            tts_queue.put((chunk_sequence, clause_buffer.strip(), True))
            chunk_sequence += 1

        # Signal TTS worker to finish
        if synthesize_voice and worker_thread:
            tts_queue.put(None)
            tts_queue.join()

        t_total = time.time() - t0
        was_interrupted = not self.barge_in_mgr.is_valid(gen_id)

        metrics = {
            "generation_id": gen_id,
            "provider": provider_name,
            "model": model_name,
            "is_offline": is_offline,
            "total_tokens": len(full_text_accumulator),
            "total_chars": sum(len(t) for t in full_text_accumulator),
            "chunks_synthesized": chunk_sequence,
            "ttft_ms": round(t_first_token * 1000.0, 1) if t_first_token else None,
            "ttfa_ms": round(t_first_audio * 1000.0, 1) if t_first_audio else None,
            "total_latency_ms": round(t_total * 1000.0, 1),
            "interrupted": was_interrupted,
        }
        self.metrics_history.append(metrics)
        if len(self.metrics_history) > 30:
            self.metrics_history.pop(0)

        logger.info(
            f"⚡ Stream done: gen={gen_id}, TTFT={metrics['ttft_ms']}ms, "
            f"TTFA={metrics['ttfa_ms']}ms, Total={metrics['total_latency_ms']}ms, "
            f"Chunks={chunk_sequence}, Interrupted={was_interrupted}"
        )

        return {
            "response": "".join(full_text_accumulator),
            "generation_id": gen_id,
            "metrics": metrics,
            "interrupted": was_interrupted,
        }

    def get_latest_metrics(self) -> Optional[Dict[str, Any]]:
        """Return the most recent latency telemetry measurements."""
        return self.metrics_history[-1] if self.metrics_history else None


# Singleton instance
_streaming_orchestrator: Optional[StreamingOrchestrator] = None


def get_streaming_orchestrator(hybrid_router=None, voice_engine=None) -> StreamingOrchestrator:
    global _streaming_orchestrator
    if _streaming_orchestrator is None:
        _streaming_orchestrator = StreamingOrchestrator(hybrid_router=hybrid_router, voice_engine=voice_engine)
    elif voice_engine and not _streaming_orchestrator.voice_engine:
        _streaming_orchestrator.voice_engine = voice_engine
    return _streaming_orchestrator
